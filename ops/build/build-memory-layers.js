/**
 * Async entry point for build-memory-layers.
 * parseSessionMemoryEntries and parseTaskMemoryEntries are now async generators
 * that stream JSONL files instead of loading entire files into memory.
 */
async function main() {
  ensureDirectory(STRUCTURED_ROOT);
  ensureDirectory(GENERATED_ROOT);

  // Read inbox entries from .md files
  const newInboxEntries = parseInboxEntries();

  // Read durable records: shared-inbox.jsonl (inbox entries) + dream-inbox.jsonl (dream writebacks)
  // dream-inbox.jsonl is written by run-memory-dream.ps1 and not regenerated by this script,
  // so dream records survive across build-memory-layers.js runs
  const existingSharedRecords = readJsonl(SHARED_INBOX_JSONL);
  const dreamRecords = readJsonl(DREAM_INBOX_JSONL)
    .map((record) =>
      repairStructuredRecord(record, {
        prefix: "dream",
        source: "dream-inbox",
        source_kind: "writeback",
        memory_level: "durable",
        visibility: "shared",
      })
    )
    .filter(Boolean);

  // Build content_hash -> record index from existing structured records.
  // This is used by the 30-second dedup window in deduplicateSharedInbox.
  const existingRecordsByHash = new Map();
  for (const rec of [...existingSharedRecords, ...dreamRecords]) {
    if (!rec || !rec.id) continue;
    const hash = rec.content_hash || sha256(rec.content || "");
    // Keep the most recent record per hash (by latest t)
    const existing = existingRecordsByHash.get(hash);
    if (!existing) {
      existingRecordsByHash.set(hash, rec);
    } else {
      const existingTs = new Date(existing.t || 0).getTime();
      const recTs = new Date(rec.t || 0).getTime();
      if (recTs > existingTs) {
        existingRecordsByHash.set(hash, rec);
      }
    }
  }

  const nowMs = Date.now();
  // parseSessionMemoryEntries and parseTaskMemoryEntries are now async —
  // they use createJsonlStream to stream JSONL files without full file buffering.
  const [sessionMemory, taskMemory] = await Promise.all([
    parseSessionMemoryEntries(),
    parseTaskMemoryEntries(),
  ]);

  const layers = {
    sharedInbox: deduplicateSharedInbox(newInboxEntries, dreamRecords, existingRecordsByHash, nowMs),
    sessionMemory,
    sharedEvents: parseEventEntries(),
    taskMemory,
  };

  writeJsonl(SHARED_INBOX_JSONL, layers.sharedInbox);
  writeJsonl(SESSION_MEMORY_JSONL, layers.sessionMemory);
  writeJsonl(SHARED_EVENTS_JSONL, layers.sharedEvents);
  writeJsonl(TASK_MEMORY_JSONL, layers.taskMemory);

  const entityExtractor = loadEntityExtractor();
  const knowledgeGraph = loadKnowledgeGraph();

  // Daily append-only logs (only touches today/yesterday files — never rewrites history)
  const allRecords = [
    ...layers.sharedInbox,
    ...layers.sessionMemory,
    ...layers.sharedEvents,
    ...layers.taskMemory,
    ...dreamRecords,   // also extract entities from dream writeback records
  ];

  // Open a KG batch so that hundreds of ingestRecord calls share one transaction
  // instead of opening/closing the DB on every call.
  try { knowledgeGraph.beginBatch(); } catch {}

  for (const record of allRecords) {
    if (record._entityExtracted) continue;  // skip already-processed records
    const enriched = entityExtractor.extractFromRecord(record);
    if (enriched.facts?.length || enriched.concepts?.length || enriched.entities?.length) {
      // Write enriched record back to the appropriate JSONL
      // (facts/concepts are included in the record for semantic-search.py to index)
      const targetFile = record._sourceFile || getTargetJsonl(record);
      if (targetFile && fs.existsSync(targetFile)) {
        patchJsonlRecord(targetFile, record.id, enriched);
      }
    }
    // Ingest into the knowledge graph
    try {
      knowledgeGraph.ingestRecord({
        ...enriched,
        source_file: record.source || record.tool || "build-memory-layers",
      });
    } catch (err) {
      // Non-fatal: KG ingestion should never block memory writes
      console.error(`[build-memory-layers] KG ingest error for ${record.id}: ${err.message}`);
    }
    record._entityExtracted = true;
  }

  try { knowledgeGraph.endBatch(true); } catch {}

  // KG batch transaction verification: confirm the committed entity count is plausible
  // (exact equality with recordCount is not expected since entities may be deduplicated
  // across records, but a dramatic mismatch signals a transaction failure)
  try {
    const preCommitEntities = 0;
    const statsBefore = knowledgeGraph.stats ? knowledgeGraph.stats() : null;
    const postCommitEntities = statsBefore ? statsBefore.entities : null;
    const expectedEntities = allRecords.filter(
      (r) => (r.entities?.length > 0) || (r.facts?.length > 0) || (r.concepts?.length > 0)
    ).length;
    if (
      typeof postCommitEntities === "number" &&
      expectedEntities > 0 &&
      postCommitEntities < Math.floor(expectedEntities * 0.05)
    ) {
      // Fewer than 5% of records produced entities — possible batch failure
      console.warn(
        `[build-memory-layers] KG batch commit mismatch: expected ~${expectedEntities} entity-producing records, ` +
        `but KG has only ${postCommitEntities} total entities. Transaction may have been rolled back.`
      );
    }
  } catch (_verifyErr) {
    // Non-fatal — verification failures must never block memory writes
  }

  appendDailyLogs(allRecords);

  // Close KG connection
  try { knowledgeGraph.close(); } catch {}

  const summary = buildLayerSummary(layers);
  writeText(MEMORY_LAYERS_MD, summary.markdown);
  writeText(MEMORY_LAYERS_JSON, `${JSON.stringify(summary.json, null, 2)}\n`);

  // Token-budgeted GLOBAL-CONTEXT body + meta (body is wrapped by memory-bus.ps1)
  const globalContext = buildGlobalContext(layers);

  // Append @include directives so tools that understand the directive can
  // lazily pull in AUTO-DREAM and HANDOFF without duplicating content.
  const bodyWithIncludes = [
    globalContext.bodyMarkdown.trimEnd(),
    "",
    "---",
    "## 更多详情",
    "",
    "@include AUTO-DREAM.md",
    "@include HANDOFF.md",
    "@include L0-bootstrap.md",
    "",
  ].join("\n");

  writeText(GLOBAL_CONTEXT_BODY_MD, bodyWithIncludes);
  writeText(GLOBAL_CONTEXT_META_JSON, `${JSON.stringify(globalContext.meta, null, 2)}\n`);

  // Rich navigable MEMORY-INDEX.md
  const memoryIndex = buildMemoryIndex(layers);
  const memoryIndexPath = path.join(GENERATED_ROOT, "MEMORY-INDEX.md");
  writeText(memoryIndexPath, memoryIndex);
  process.stderr.write(`[memory-index] wrote ${memoryIndexPath} (${memoryIndex.length} chars)\n`);

  // Phase 2 L0-L1 bootstrap — runs after all layers are written
  try {
    const { buildL0L1Bootstrap } = require("./build-l0-l1-bootstrap.js");
    buildL0L1Bootstrap(process.cwd());
  } catch (e) {
    process.stderr.write(`[L0-L1] bootstrap skipped: ${e.message}\n`);
  }

  process.stdout.write(
    JSON.stringify(
      {
        ok: true,
        generatedAt: summary.json.generatedAt,
        counts: summary.json.counts,
        files: {
          sharedInbox: SHARED_INBOX_JSONL,
          sessionMemory: SESSION_MEMORY_JSONL,
          sharedEvents: SHARED_EVENTS_JSONL,
          taskMemory: TASK_MEMORY_JSONL,
          layersMarkdown: MEMORY_LAYERS_MD,
          layersJson: MEMORY_LAYERS_JSON,
          globalContextMarkdown: CTX_GLOBAL_CONTEXT_MD,
          globalContextMetaJson: GLOBAL_CONTEXT_META_JSON,
          globalContextBodyMarkdown: GLOBAL_CONTEXT_BODY_MD,
          memoryIndexMarkdown: memoryIndexPath,
        },
      },
      null,
      2
    )
  );
}

main();
